if __name__ == "__main__":
    timeline_clip = timeline()

    def write_mlt_file(dest: str):
        mlt = MltXml(timeline_clip, name="atsc_720p_30")
        with open(dest, "w") as f:
            f.write(mlt.render())

    def render_video(mlt_file: str, dest: str = "render.mp4"):
        subprocess.run(
            [
                "melt",
                mlt_file,
                "-consumer",
                f"avformat:{dest}",
                "vcodec=libx264",
                "crf=18",
                "preset=fast",
                "pix_fmt=yuv420p",
                "acodec=aac",
                "ab=192k",
                "threads=0",
            ],
            check=True,
        )

    def preview_video(mlt_file: str):
        subprocess.run(["melt", mlt_file])

    def render_srt(dest: str = "render.srt"):
        sub_str = Subtitle.gen_srt(timeline_clip.subs())
        with open(dest, "w") as f:
            f.write(sub_str)

    parser = argparse.ArgumentParser("Video Render")
    parser.add_argument("output_name", default="render", nargs="?")
    parser.add_argument("--subtitle_only", default=False, action="store_true")
    parser.add_argument("--preview_only", default=False, action="store_true")
    args = parser.parse_args()
    render_srt(f"{args.output_name}.srt")
    mlt_file = f"{args.output_name}.mlt"
    write_mlt_file(mlt_file)
    if args.preview_only:
        preview_video(mlt_file)
    if not args.subtitle_only and not args.preview_only:
        render_video(mlt_file, f"{args.output_name}.mp4")
